"""Reconstruct the corrected terminal field from saved two-anchor networks."""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from PINN.pinn_model import network
from PINN.refinement import assemble, evaluate_block


def reconstruct(folder):
    records = json.loads((folder / "blocks.json").read_text(encoding="utf-8"))
    if not isinstance(records, list):
        raise ValueError("Use a model directory generated by the two-anchor training entry point")
    coarse = np.load(folder / "coarse.npy")
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = network().to(device).eval()
    def predictions():
        for record in records:
            model.load_state_dict(torch.load(folder / record["file"], map_location=device, weights_only=True))
            bounds = record["bounds"]
            yield bounds, evaluate_block(model, record["offset"], record["amplitude"], coarse.shape, bounds, device)
    return assemble(coarse, predictions())


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model_dir", type=Path)
    parser.add_argument("output")
    args = parser.parse_args()
    np.save(args.output, reconstruct(args.model_dir))
